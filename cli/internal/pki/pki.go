// Package pki implements the Holism PKI: one long-lived root CA per swarm
// deployment and short-lived leaf certificates issued from it. See
// docs/design/agent-swarm-framework.md sections 6.1 and 6.2.
//
// The PKI lives in a single directory (default ./pki/) holding ca.key and
// ca.crt. Leaf certificates are added by later CLI slices (cert issue/renew).
package pki

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"os"
	"path/filepath"
	"time"
)

// LeafLifetime is the validity of certificates issued by the Holism CA.
// Leaves live for about one month and are renewed before expiry.
const LeafLifetime = 30 * 24 * time.Hour

// CALifetime is the validity of the root CA generated by `holism init`.
const CALifetime = 10 * 365 * 24 * time.Hour

// File names inside the PKI directory.
const (
	CAKeyFile  = "ca.key"
	CACertFile = "ca.crt"
)

// DefaultDir is the default PKI directory, relative to the working directory.
const DefaultDir = "pki"

// Config describes the on-disk PKI layout.
type Config struct {
	// Dir is the PKI directory holding the CA material.
	Dir string
}

// DefaultConfig returns the Config for the default ./pki directory.
func DefaultConfig() Config {
	return Config{Dir: DefaultDir}
}

// CAKeyPath returns the path of the root CA private key.
func (c Config) CAKeyPath() string { return filepath.Join(c.Dir, CAKeyFile) }

// CACertPath returns the path of the root CA certificate.
func (c Config) CACertPath() string { return filepath.Join(c.Dir, CACertFile) }

// Initialized reports whether the PKI directory already holds a CA pair.
func (c Config) Initialized() bool {
	_, keyErr := os.Stat(c.CAKeyPath())
	_, certErr := os.Stat(c.CACertPath())
	return keyErr == nil && certErr == nil
}

// GenerateCA creates a new self-signed root CA (ECDSA P-256, CALifetime
// validity) in the PKI directory and returns the parsed certificate and key.
// It refuses to overwrite an existing PKI unless force is true.
func GenerateCA(c Config, force bool) (*x509.Certificate, *ecdsa.PrivateKey, error) {
	if c.Initialized() && !force {
		return nil, nil, fmt.Errorf("PKI already initialized in %s (use --force to overwrite)", c.Dir)
	}

	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, nil, fmt.Errorf("generate CA key: %w", err)
	}

	serial, err := randomSerial()
	if err != nil {
		return nil, nil, fmt.Errorf("generate CA serial: %w", err)
	}

	now := time.Now()
	template := &x509.Certificate{
		SerialNumber: serial,
		Subject: pkix.Name{
			CommonName:   "holism root CA",
			Organization: []string{"holism"},
		},
		// NotBefore is backdated slightly to tolerate clock skew.
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(CALifetime),
		IsCA:                  true,
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageCRLSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
	}

	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		return nil, nil, fmt.Errorf("create CA certificate: %w", err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, nil, fmt.Errorf("parse CA certificate: %w", err)
	}

	if err := c.SaveCA(key, cert); err != nil {
		return nil, nil, fmt.Errorf("save CA: %w", err)
	}
	return cert, key, nil
}

// SaveCA writes the root CA key (0600) and certificate (0644) into the PKI
// directory, creating it if needed.
func (c Config) SaveCA(key *ecdsa.PrivateKey, cert *x509.Certificate) error {
	if err := os.MkdirAll(c.Dir, 0o755); err != nil {
		return err
	}

	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return fmt.Errorf("marshal CA key: %w", err)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER})
	if err := writeFile(c.CAKeyPath(), keyPEM, 0o600); err != nil {
		return err
	}

	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: cert.Raw})
	return writeFile(c.CACertPath(), certPEM, 0o644)
}

// LoadCA reads and parses the root CA key and certificate from the PKI
// directory. It fails if either file is missing, unparseable, or if the
// certificate's public key does not match the private key.
func LoadCA(c Config) (*x509.Certificate, *ecdsa.PrivateKey, error) {
	keyPEM, err := os.ReadFile(c.CAKeyPath())
	if err != nil {
		return nil, nil, fmt.Errorf("read CA key: %w", err)
	}
	keyBlock, _ := pem.Decode(keyPEM)
	if keyBlock == nil || keyBlock.Type != "PRIVATE KEY" {
		return nil, nil, fmt.Errorf("%s is not a PEM private key", c.CAKeyPath())
	}
	keyAny, err := x509.ParsePKCS8PrivateKey(keyBlock.Bytes)
	if err != nil {
		return nil, nil, fmt.Errorf("parse CA key: %w", err)
	}
	key, ok := keyAny.(*ecdsa.PrivateKey)
	if !ok {
		return nil, nil, fmt.Errorf("CA key is %T, want ECDSA", keyAny)
	}

	certPEM, err := os.ReadFile(c.CACertPath())
	if err != nil {
		return nil, nil, fmt.Errorf("read CA cert: %w", err)
	}
	certBlock, _ := pem.Decode(certPEM)
	if certBlock == nil || certBlock.Type != "CERTIFICATE" {
		return nil, nil, fmt.Errorf("%s is not a PEM certificate", c.CACertPath())
	}
	cert, err := x509.ParseCertificate(certBlock.Bytes)
	if err != nil {
		return nil, nil, fmt.Errorf("parse CA cert: %w", err)
	}

	pub, ok := cert.PublicKey.(*ecdsa.PublicKey)
	if !ok || !pub.Equal(&key.PublicKey) {
		return nil, nil, errors.New("CA certificate does not match CA key")
	}
	return cert, key, nil
}

// randomSerial returns a random 128-bit certificate serial number.
func randomSerial() (*big.Int, error) {
	limit := new(big.Int).Lsh(big.NewInt(1), 128)
	return rand.Int(rand.Reader, limit)
}

// writeFile writes data to path via a temp file + rename so a crash cannot
// leave a truncated file behind.
func writeFile(path string, data []byte, perm os.FileMode) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, perm); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
